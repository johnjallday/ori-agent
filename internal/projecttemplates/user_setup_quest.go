func cloneUserQuestLaunch(source *specialist.WorkspaceLaunchCopy) *specialist.WorkspaceLaunchCopy {
	if source == nil {
		return nil
	}
	clone := *source
	return &clone
}

func digestUserQuestBytes(value []byte) string {
	sum := sha256.Sum256(value)
	return hex.EncodeToString(sum[:])
}
